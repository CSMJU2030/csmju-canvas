/// คะแนนความเกี่ยวข้องอย่างง่าย: ชื่อเรื่อง > คำสำคัญ > สรุป > เนื้อหา
export function searchHelp(query: string, limit = 5): HelpArticle[] {
  const q = query.trim().toLowerCase();

  if (!q) return [];

  const terms = q.split(/\s+/).filter(Boolean);

  return HELP_ARTICLES.map((article) => {
    let score = 0;

    for (const term of terms) {
      if (article.title.toLowerCase().includes(term)) score += 5;
      if (article.keywords.some((k) => k.toLowerCase().includes(term) || term.includes(k.toLowerCase()))) score += 4;
      if (article.summary.toLowerCase().includes(term)) score += 2;
      if (article.body.some((line) => line.toLowerCase().includes(term))) score += 1;
    }

    return { article, score };
  })
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((entry) => entry.article);
}
